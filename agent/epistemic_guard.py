class VerificationPipeline:
    """
    Queues speculative facts for verification.
    Uses web search to test claims against reality.
    Runs periodically as a separate phase in the brain cycle.
    """

    def __init__(self, db_path: Path = DB_PATH):
        self.db_path = db_path
        self._local = threading.local()
        self.guard = EpistemicGuard(db_path)

    @property
    def conn(self):
        if not hasattr(self._local, 'conn') or self._local.conn is None:
            self._local.conn = sqlite3.connect(str(self.db_path))
            self._local.conn.row_factory = sqlite3.Row
        return self._local.conn

    def get_verification_queue(self, limit: int = 5) -> List[Dict]:
        """Get facts that need verification (speculative ring, not yet verified)."""
        rows = self.conn.execute(
            """SELECT id, content, source, trust, category
            FROM semantic_facts
            WHERE trust < 0.4
              AND source LIKE 'brain-%'
              AND (tags NOT LIKE '%verified%' OR tags IS NULL)
            ORDER BY RANDOM() LIMIT ?""",
            (limit,)
        ).fetchall()
        return [dict(r) for r in rows]

    def verify_fact(self, fact: Dict, search_results: List[str]) -> Dict:
        """
        Compare a fact against search results.
        Returns verdict: confirmed, contradicted, or unchanged.
        """
        content = fact["content"]
        evidence = "\n".join(search_results[:5])

        # Simple keyword overlap check (no model needed)
        content_lower = content.lower()
        keywords = [w for w in content_lower.split()
                    if len(w) > 4 and w not in {"about", "their", "these", "those",
                       "which", "could", "would", "should", "might", "being",
                       "having", "where", "there", "other", "into", "more",
                       "some", "such", "than", "that", "this", "what", "when"}]

        confirmed_keywords = sum(1 for k in keywords[:10] if k in evidence.lower())
        ratio = confirmed_keywords / max(1, len(keywords[:10]))

        if ratio > 0.4:
            return {"verdict": "confirmed", "overlap": ratio}
        elif ratio < 0.1 and len(evidence) > 100:
            return {"verdict": "contradicted", "overlap": ratio}
        else:
            return {"verdict": "unchanged", "overlap": ratio}

    def apply_verification(self, fact_id: int, verdict: str):
        """Update a fact's trust based on verification result."""
        if verdict == "confirmed":
            # Boost trust, but don't exceed derived ceiling (0.6)
            self.conn.execute(
                "UPDATE semantic_facts SET trust = MIN(trust + 0.2, 0.6) WHERE id = ?",
                (fact_id,)
            )
            self.conn.execute(
                "UPDATE semantic_facts SET tags = COALESCE(tags || ',verified', 'verified') WHERE id = ?",
                (fact_id,)
            )
        elif verdict == "contradicted":
            # Slash trust
            self.conn.execute(
                "UPDATE semantic_facts SET trust = trust * 0.3 WHERE id = ?",
                (fact_id,)
            )
            self.conn.execute(
                "UPDATE semantic_facts SET tags = COALESCE(tags || ',contradicted', 'contradicted') WHERE id = ?",
                (fact_id,)
            )
        self.conn.commit()

    def close(self):
        self.guard.close()
        if hasattr(self._local, 'conn') and self._local.conn is not None:
            self._local.conn.close()
            self._local.conn = None


